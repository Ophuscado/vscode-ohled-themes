/**
 * Monochrome colour theme template: every colour is the foreground, the
 * background, or the foreground at a reduced opacity.
 */

const channels = (colour) =>
  [1, 3, 5].map((i) => parseInt(colour.slice(i, i + 2), 16));
const hex = (byte) => byte.toString(16).padStart(2, "0");

/** WCAG 2 relative luminance of an opaque colour. */
const luminance = (colour) => {
  const [r, g, b] = channels(colour)
    .map((c) => c / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

/** WCAG 2 contrast ratio of two opaque colours, from 1 to 21. */
const contrast = (a, b) => {
  const [high, low] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (high + 0.05) / (low + 0.05);
};

